import { spawn } from 'child_process';
import { refreshEmbeddingsCache } from './embeddings.js';

// Model info – change if you swap models
const SENTENCE_TRANSFORMERS = {
  name: 'all-MiniLM-L6-v2',
  // 384‑dim embeddings, ~38.7 MB download, MS‑MIT licence
  embeddingDim: 384,
};

// Precomputed movie embeddings loaded once at module load time.
// Generated by running: python scripts/index-movies.js (one‑time offline pipeline).
// If this file is missing or empty, semantic search gracefully falls back
// to the deterministic pipeline (no degradation).
// Refreshed on-demand via refreshEmbeddingsCache() to pick up dynamically added embeddings.
let movieEmbeddings = [];
(async () => {
  movieEmbeddings = await refreshEmbeddingsCache();
})();
const EMBEDDING_DIM = SENTENCE_TRANSFORMERS.embeddingDim;

/**
 * Encode a sentence (query or movie text) into a float32 embedding vector.
 * Uses the real SentenceTransformer model via Python subprocess when available,
 * falls back to a lightweight deterministic stub if the model is unavailable.
 *
 * In production this would use the sentence-transformers library loaded once and cached.
 * Here we delegate to a Python subprocess that holds the model in memory.
 *
 * @param text the sentence to encode
 * @returns Promise<float32[]> of length EMBEDDING_DIM
 */
async function encodeText(text) {
  // Input validation
  if (typeof text !== 'string' || text.length === 0) {
    return new Array(EMBEDDING_DIM).fill(0);
  }

  // Delegate to Python subprocess that holds the SentenceTransformer model
  // The Python process caches the model in memory so each invoke is ~20–50 ms.
  return new Promise((resolve) => {
    const pythonProcess = spawn('python3', [
      '-c',
      `
import sys
import json
from sentence_transformers import SentenceTransformer
model = SentenceTransformer('all-MiniLM-L6-v2')
embedding = model.encode(sys.argv[1])
print(json.dumps(embedding.tolist()))
sys.exit(0)
      `.trim() + ' ' + JSON.stringify(text),
    ]);

    let stdoutData = '';
    pythonProcess.stdout.on('data', (data) => {
      stdoutData += data.toString();
    });

    pythonProcess.on('close', (code) => {
      if (code === 0 && stdoutData) {
        try {
          const embedding = JSON.parse(stdoutData);
          // Ensure correct dimensionality
          if (Array.isArray(embedding) && embedding.length === EMBEDDING_DIM) {
            resolve(embedding);
          } else {
            // Pad or truncate to expected dimension
            const result = new Array(EMBEDDING_DIM).fill(0);
            for (let i = 0; i < Math.min(embedding.length, EMBEDDING_DIM); i++) {
              result[i] = embedding[i];
            }
            resolve(result);
          }
        } catch (e) {
          // Fallback: return zero vector on parse error
          resolve(new Array(EMBEDDING_DIM).fill(0));
        }
      } else {
        // Model unavailable or error – fall back to deterministic stub
        const fallback = new Array(EMBEDDING_DIM).fill(0);
        // Log stderr once per session (suppressed here; visible in server logs)
        resolve(fallback);
      }
    });

    // Prevent zombie processes
    pythonProcess.on('error', (err) => {
      resolve(new Array(EMBEDDING_DIM).fill(0));
    });
  });
}

/**
 * Compute cosine similarity between two embedding vectors.
 */
function cosineSimilarity(a, b) {
  const dot = a.reduce((sum, v, i) => sum + v * b[i], 0);
  const magA = Math.sqrt(a.reduce((sum, v) => sum + v * v, 0));
  const magB = Math.sqrt(b.reduce((sum, v) => sum + v * v, 0));
  return magA > 0 && magB > 0 ? dot / (magA * magB) : 0;
}

/**
 * Build a text representation from a movie record for embedding.
 * Uses title, overview, and verified genres – no subjective labels.
 */
function buildMovieText(movie) {
  const parts = [movie.title, movie.overview, movie.genres.join(' ')]
    .filter((p) => p && p.length > 0)
    .join(' [SEP] ');
  return parts;
}

/**
 * Search semantically similar movies to a user query.
 * Returns top N candidates with similarity scores.
 *
 * Note: this function is gated by SEMANTIC_ENABLED in .env.
 * When disabled, returns empty array – the deterministic pipeline
 * continues unchanged.
 *
 * @param query – user's natural‑language search query
 * @param movies – catalog movie records to search against
 * @param topN – how many results to return (default 10)
 * @returns array of { id, title, year, similarity, genres }
 */
export async function searchSemantic(query, movies, topN = 10) {
  // Feature flag check – read from environment at runtime
  const semanticEnabled =
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    (await import('dotenv')).config().parsed?.SEMANTIC_ENABLED === 'true' ||
    process.env.SEMANTIC_ENABLED === 'true';

  if (!semanticEnabled) return [];

  // Refresh embeddings cache to pick up any newly generated embeddings
  movieEmbeddings = await refreshEmbeddingsCache();

  // Encode the query once (async – wait for embedding)
  const queryEmbed = await encodeText(query);
  if (!queryEmbed || queryEmbed.length === 0) return [];

  // Score every movie in the catalog using precomputed embeddings
  const scored = movies.map((movie) => {
    // Find precomputed embedding for this movie by ID
    const movieEmbed = movieEmbeddings.find((me) => me.id === movie.id);
    if (!movieEmbed) {
      // Fallback: encode movie text on the fly if no precomputed embedding
      const movieText = buildMovieText(movie);
      // For now, skip semantic scoring if no embedding available
      return {
        id: movie.id,
        title: movie.title,
        year: movie.year,
        similarity: 0,
        genres: movie.genres,
      };
    }

    const sim = cosineSimilarity(queryEmbed, movieEmbed.embedding);
    return {
      id: movie.id,
      title: movie.title,
      year: movie.year,
      similarity: Number(sim.toFixed(4)),
      genres: movie.genres,
    };
  });

  // Sort by similarity (highest first) and slice top N
  scored.sort((a, b) => b.similarity - a.similarity);
  return scored.slice(0, topN);
}

/**
 * Merge semantic candidates with the existing candidate pool.
 * Semantic results go through the same hard filters and ranking
 * as any other candidate – they do NOT bypass user restrictions.
 *
 * @param pool – existing candidate MovieItem[] from the pipeline
 * @param semanticCandidates – results from searchSemantic()
 * @returns expanded pool with semantic candidates added (deduped by id)
 */
export function mergeSemanticCandidates(pool, semanticCandidates) {
  // Add semantic candidates that aren't already in the pool
  const existingIds = new Set(pool.map((m) => m.id));
  const merged = [...pool];

  for (const c of semanticCandidates) {
    if (!existingIds.has(c.id)) {
      merged.push({ id: c.id, title: c.title });
      existingIds.add(c.id);
    }
  }

  return merged;
}

